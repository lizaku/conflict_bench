"""Step 5 - export.  contexts + measured + beliefs -> the benchmark files

    instances.jsonl   everything: labels, answers, targets, M's behaviour
    public.jsonl      what a method receives: question, sentences, format
    card.md           the funnel, the rejections, and examples to read by hand
"""
import random
from collections import Counter, defaultdict

from conflict_bench.api import PublicInstance
from conflict_bench.construct.common import (model_dir, read_jsonl, seed_dir,
                                             write_jsonl)


def merge(cfg) -> list:
    d = model_dir(cfg)
    measured = {m["instance_id"]: m for m in read_jsonl(d / "measured.jsonl")}
    beliefs = {b["fact_id"]: b for b in read_jsonl(d / "beliefs.jsonl")}
    out = []
    for rec in read_jsonl(d / "contexts.jsonl"):
        b = beliefs.get(rec["group"], {})
        rec["confidence"] = {"entropy_q": b.get("entropy_q"),
                             "p_a_q": b.get("p_a_q"),
                             "sample_agree": b.get("sample_agree"),
                             "forms_agree": b.get("forms_agree")}
        m = measured.get(rec["instance_id"])
        rec["measured"] = m is not None
        if m:
            rec["d"], rec["d0"] = m["d"], m["d0"]
            rec["confidence"].update(
                entropy_qc=m.get("entropy_qc"), logp_qc=m["logp_qc"],
                logp_q=m["logp_q"])
        out.append(rec)
    return out


def _table(rows, header):
    lines = ["| " + " | ".join(header) + " |",
             "|" + "|".join("---" for _ in header) + "|"]
    lines += ["| " + " | ".join(str(c) for c in r) + " |" for r in rows]
    return "\n".join(lines)


def _show(rec) -> str:
    lines = [f"**`{rec['recipe']}` / {rec['format']}** — `{rec['instance_id']}`, "
             f"relation {rec['relation']}, state {rec['state']}", ""]
    for p in rec["passages"]:
        for c in p["chunks"]:
            mark = "" if c["label"] == "supports" and c["role"] == "filler" \
                else f"  ← {c['label']}"
            lines.append(f"- [{p['id']}] {c['text']}{mark}")
    lines.append(f"- **Q:** {rec['question']}")
    lines.append(f"- path: " + "; ".join(
        f"{p['state']} / a = {p['a']} / context says {p['asserted']} → "
        f"**{p['label']}**" for p in rec["path"]))
    lines.append(f"- conflict for q = {rec['labels']['conflict_q']}, "
                 f"any conflict = {rec['labels']['conflict_global']}, "
                 f"targets = {rec['targets']}")
    if rec.get("d"):
        lines.append(f"- d = “{rec['d']['text']}” (names {rec['d']['matches']}); "
                     f"d0 = “{rec['d0']['text']}”")
    return "\n".join(lines)


def card(cfg, instances) -> str:
    d = model_dir(cfg)
    beliefs = read_jsonl(d / "beliefs.jsonl")
    rejected = read_jsonl(seed_dir(cfg) / "rejected.jsonl") + \
        read_jsonl(d / "rejected.jsonl")
    n_seed = len(read_jsonl(seed_dir(cfg) / "facts.jsonl"))
    states = Counter(b["state"] for b in beliefs)
    out = [f"# Benchmark card — {instances[0]['model'] if instances else '?'}", "",
           "Generated by `construct/export.py`. Every label is relative to this "
           "model.", "", "## Funnel", "",
           _table([["seed facts", n_seed],
                   ["facts elicited", len(beliefs)],
                   ["  known", states["known"]],
                   ["  known, answer equals the seed's",
                    sum(b["state"] == "known" and b["a_equals_gold"] for b in beliefs)],
                   ["  uncertain", states["uncertain"]],
                   ["  unknown", states["unknown"]],
                   ["facts with at least one instance",
                    len({i["group"] for i in instances})],
                   ["instances", len(instances)],
                   ["instances measured", sum(i["measured"] for i in instances)]],
                  ["stage", "count"]), ""]

    out += ["## Instances per recipe", ""]
    by = defaultdict(list)
    for i in instances:
        by[i["recipe"]].append(i)
    rows = []
    for r, xs in sorted(by.items()):
        m = [x for x in xs if x["measured"]]
        def rate(key, xs=m):
            hits = [x for x in xs if x["targets"].get(key)
                    and x["d"]["matches"] == [x["targets"][key]]]
            den = [x for x in xs if x["targets"].get(key)]
            return f"{len(hits)}/{len(den)}" if den else "–"
        rows.append([r, len(xs), sum(x["format"] == "short" for x in xs),
                     sum(x["format"] == "cloze" for x in xs),
                     sum(x["has_uncertain"] for x in xs),
                     sum(x["labels"]["conflict_q"] for x in xs),
                     sum(x["labels"]["conflict_global"] for x in xs),
                     rate("ctx"), rate("mem")])
    out += [_table(rows, ["recipe", "n", "short", "cloze", "uncertain",
                          "conflict for q", "any conflict",
                          "d = context target", "d = memory target"]), "",
            "The last two columns are the model's default behaviour (no "
            "method): how often `d` names exactly the target of each "
            "direction.", ""]

    reasons = Counter((r["step"], r["reason"]) for r in rejected)
    out += ["## Rejections", "",
            _table([[s, r, n] for (s, r), n in reasons.most_common()],
                   ["step", "reason", "facts"]), ""]

    out += ["## Examples (3 per recipe, drawn at random — read them)", ""]
    rng = random.Random(cfg.get("seed", 0))
    for r, xs in sorted(by.items()):
        for rec in rng.sample(xs, min(3, len(xs))):
            out += [_show(rec), ""]
    return "\n".join(out)


def run(cfg):
    d = model_dir(cfg)
    instances = merge(cfg)
    write_jsonl(d / "instances.jsonl", instances)
    write_jsonl(d / "public.jsonl",
                [PublicInstance.from_record(r).public_record() for r in instances])
    (d / "card.md").write_text(card(cfg, instances), encoding="utf-8")
    n = sum(i["measured"] for i in instances)
    print(f"[export] {len(instances)} instances ({n} measured) -> "
          f"{d / 'instances.jsonl'}, public.jsonl, card.md")
    return instances
